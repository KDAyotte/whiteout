// Shrinks the generated card/location art into assets/art-web and writes src/art.gen.js.
// Usage: node prep-art.mjs   (run before node build.mjs whenever art changes)
import sharp from 'sharp';
import { readdirSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';

const SRC = 'assets/meshy_output/art', OUT = 'assets/art-web';
mkdirSync(OUT, { recursive: true });
const keys = [];

// card + location art (3:2) -> 768x512 JPEG
for (const dir of readdirSync(SRC, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const src = `${SRC}/${dir.name}/image_0.png`;
  if (!existsSync(src)) continue;
  await sharp(src).resize(768, 512, { fit: 'cover' }).jpeg({ quality: 80, mozjpeg: true }).toFile(`${OUT}/${dir.name}.jpg`);
  keys.push(dir.name);
}
// survivor portraits from the miniature concept art (square) -> crop upper body to 3:2
for (const s of ['mara', 'jonas', 'priya', 'tuck']) {
  const src = `assets/meshy_output/minis/concept-${s}/image_0.png`;
  if (!existsSync(src)) continue;
  await sharp(src).extract({ left: 112, top: 30, width: 800, height: 533 }).resize(768, 512)
    .jpeg({ quality: 82, mozjpeg: true }).toFile(`${OUT}/v-${s}.jpg`);
  keys.push(`v-${s}`);
}
keys.sort();
const ident = k => 'a_' + k.replace(/[^a-z0-9]/gi, '_');
writeFileSync('src/art.gen.js',
  '// Generated by prep-art.mjs. Do not edit.\n' +
  keys.map(k => `import ${ident(k)} from '../${OUT}/${k}.jpg';`).join('\n') +
  `\nexport const ART_URLS = {\n${keys.map(k => `  '${k}': ${ident(k)},`).join('\n')}\n};\n`);
console.log(`${keys.length} images prepared`);
